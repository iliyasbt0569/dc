function findQuestionAndAnswer(selectedText) {
  for (let pair of qaPairs) {
    if (pair.question.includes(selectedText) || pair.answer.includes(selectedText)) {
      return `q: ${pair.question}\nvr: ${pair.answer}`;
    }
  }
  return '';
}

